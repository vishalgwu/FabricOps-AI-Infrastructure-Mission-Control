"""Renders the evaluation report as Markdown. The output is deterministic (no timestamps or timings),
so a test can check that the committed report is up to date."""
from evals.dataset import Dataset
from evals.metrics import Metric, compute, outcome_counts
from evals.runner import CaseResult

REPORT_PATH_HINT = "docs/evaluation/EVAL_REPORT.md"


def render(dataset: Dataset, results: list[CaseResult]) -> str:
    results = sorted(results, key=lambda r: r.case.id)
    metrics = compute(results)
    lines: list[str] = []
    w = lines.append
    w("# FabricOps Evaluation Report")
    w("")
    w(f"Dataset version **{dataset.dataset_version}**, **{len(results)} cases**. Generated by `python -m evals --write-report`; "
      "a test fails if this file is out of date.")
    w("")
    w("## Read this first")
    w("")
    w("- **This measures the safeguards around the model, not the model.** Every case scripts what the model does "
      "(one good answer, or one specific kind of bad answer) and checks that the *system* behaves correctly: it abstains on bad "
      "data, refuses invented IDs, blocks out-of-scope proposals, classifies risk itself, and holds risky proposals for a human.")
    w("- **No real model was used.** Nothing here says how good Claude's hypotheses are. Claim support (are the claims actually "
      "supported by the evidence?) needs a person; see [the rubric](CLAIM_SUPPORT_RUBRIC.md). **No manual claim-support review "
      "has been done yet.**")
    w("- **The sample is tiny and synthetic**: one fixture per scenario and a handful of cases per failure type. The numbers below "
      "are counts out of small totals. They are not statistically meaningful and are not an accuracy estimate. A result of 5/5 "
      "means \"every case written passed\", not \"5 out of 5 would pass in general\".")
    w("- **The cases were written alongside the safeguards they test**, so they cover what was thought of. "
      "Cases nobody thought of are not covered.")
    w("- **Latency and token cost are not reported.** With a scripted model they are meaningless. The optional live smoke test "
      "(`python -m evals.live`, needs an API key) records them; it has not been run.")
    w("")
    w("## Results")
    w("")
    w("| Metric | Result | Critical | What is counted |")
    w("|---|---|---|---|")
    for m in metrics:
        w(f"| {m.name} | **{m.text}** | {'yes' if m.critical else 'no'} | {m.what} |")
    w("")
    caveats = [m for m in metrics if m.caveat]
    if caveats:
        w("Caveats on specific metrics:")
        w("")
        for m in caveats:
            w(f"- *{m.name}*: {m.caveat}")
        w("")
    failing = [m for m in metrics if not m.ok]
    w("**Critical metrics:** " + ("all at full count." if not any(m.critical and not m.ok for m in metrics)
                                  else "NOT all at full count: " + ", ".join(m.name for m in failing if m.critical)))
    w("")
    w("### Workflow outcomes")
    w("")
    w("| Final run status | Cases |")
    w("|---|---|")
    for status, n in outcome_counts(results).items():
        w(f"| {status} | {n} |")
    w("")
    w("## Cases")
    w("")
    w("Every case has an expected behaviour defined in `backend/data/evals/dataset.v1.json`, outside anything the model sees.")
    w("")
    w("| ID | Case | Covers | Expected | Observed | Result |")
    w("|---|---|---|---|---|---|")
    for r in results:
        e = r.case.expected
        expected = e.run_status or "—"
        if e.error_code:
            expected += f" ({e.error_code})"
        observed = r.facts["status"] + (f" ({r.facts['error_code']})" if r.facts["error_code"] else "")
        w(f"| {r.case.id} | {r.case.title} | {r.case.covers} | {expected} | {observed} | {'pass' if r.passed else '**FAIL**'} |")
    w("")
    gaps = [r for r in results if r.case.expected.known_gap]
    w("## Known gaps (things the system does not catch)")
    w("")
    if not gaps:
        w("None recorded.")
    for r in gaps:
        w(f"- **{r.case.id}, {r.case.title}.** {r.case.expected.known_gap}")
    w("")
    w("## What is not covered")
    w("")
    w("- Real model behaviour: hallucination rate, how often it abstains when it should, quality of its next-step suggestions.")
    w("- Whether cited documents genuinely support the claims they are attached to.")
    w("- Real telemetry: the data is fabricated, clean and small, so noisy or very large inputs are untested.")
    w("- Load, concurrency beyond a few threads, and a server crash during a run (Phase 11).")
    w("- Anything about the UI beyond its own tests (see the frontend test suite).")
    w("")
    w("## Failed checks")
    w("")
    bad = [(r, c) for r in results for c in r.checks if not c.ok]
    if not bad:
        w("None.")
    for r, c in bad:
        w(f"- {r.case.id} / {c.name}: {c.detail}")
    w("")
    return "\n".join(lines)


def summary(metrics: list[Metric]) -> str:
    def mark(m: Metric) -> str:
        if not m.critical:
            return "info"
        return "ok  " if m.ok else "BAD "

    return "\n".join(f"{mark(m)} {m.name}: {m.text}" for m in metrics)
